"""Extraction, scored against the gold set that cost no lawyer hours.

Every document was generated from the ground truth, and the manifest says which
facts it carries. A predicted fact is correct when its predicate, subject and
linked object match a manifest fact of the same document. Precision and recall
per relation type and per document type, at three confidence thresholds — and
the facts that could not be linked, with the reason, because that is where a
firm's names cost recall. The number that transfers is the method, not the score:
the documents are template-written, so these scores are an upper bound.
"""

from __future__ import annotations

from collections import defaultdict

from ..ingest.docgraph import LinkStats, Lookups, linked_facts
from ..ingest.documents import Document
from ..semantic.templates import expand

THRESHOLDS = (0.5, 0.7, 0.9)


def _gold_object(obj: str) -> str:
    return expand(obj)


def score(docs: list[Document], extraction: dict[str, dict], texts: dict[str, str],
          lookups: Lookups) -> dict:
    stats = LinkStats()
    per: dict[tuple, dict[str, int]] = defaultdict(lambda: {"tp": 0, "fp": 0, "fn": 0})
    extracted_docs = 0
    for d in docs:
        row = extraction.get(d.doc_id)
        if row is None:
            continue
        extracted_docs += 1
        gold = {(f["predicate"], _gold_object(f["object"])) for f in d.facts}
        predicted = linked_facts(d, row, texts.get(d.doc_id, ""), lookups, stats)
        for t in THRESHOLDS:
            kept = {(f["predicate"], f["object"]) for f in predicted if f["confidence"] >= t}
            for pred, obj in kept:
                hit = (pred, obj) in gold
                for dim in (("relation", pred), ("doc_type", d.doc_type), ("all", "all")):
                    per[(t, *dim)]["tp" if hit else "fp"] += 1
            for pred, _obj in gold - kept:
                for dim in (("relation", pred), ("doc_type", d.doc_type), ("all", "all")):
                    per[(t, *dim)]["fn"] += 1
    return {"docs": extracted_docs, "cells": dict(per), "stats": stats}


def _pr(cell: dict[str, int]) -> tuple[str, str]:
    tp, fp, fn = cell["tp"], cell["fp"], cell["fn"]
    p = f"{tp / (tp + fp):.2f}" if tp + fp else "—"
    r = f"{tp / (tp + fn):.2f}" if tp + fn else "—"
    return p, r


def render(result: dict, model: str, total_docs: int, refused: int, errored: int) -> str:
    cells, stats = result["cells"], result["stats"]
    lines = [
        "# Extraction against the gold set",
        "",
        "Generated by `make reports` from `data/fixtures/extraction.jsonl` (Claude, via the",
        f"Message Batches API; model `{model}`) and the generation manifest in",
        "`data/fixtures/documents.jsonl`. A fact is correct when predicate, subject and",
        "*linked* object match a fact the document was generated to carry.",
        "",
        "> The documents are template-written, so the prose is more regular than a firm's.",
        "> Read these scores as an upper bound, and the method as the transferable part: a",
        "> firm reproduces the table on its own corpus with a few hundred reviewed documents.",
        "",
        f"Documents: {total_docs} · extracted: {result['docs']} · refused: {refused} · "
        f"errored: {errored}",
        "",
        "## By relation",
        "",
        "| relation | " + " | ".join(f"P@{t} | R@{t}" for t in THRESHOLDS) + " |",
        "|---|" + "---|---|" * len(THRESHOLDS),
    ]
    dims = sorted({(k[1], k[2]) for k in cells})
    for kind in ("relation", "doc_type", "all"):
        if kind == "doc_type":
            lines += ["", "## By document type", "",
                      "| document type | " + " | ".join(f"P@{t} | R@{t}" for t in THRESHOLDS)
                      + " |", "|---|" + "---|---|" * len(THRESHOLDS)]
        if kind == "all":
            lines += ["", "## Overall", "",
                      "| | " + " | ".join(f"P@{t} | R@{t}" for t in THRESHOLDS) + " |",
                      "|---|" + "---|---|" * len(THRESHOLDS)]
        for k, name in dims:
            if k != kind:
                continue
            row = []
            for t in THRESHOLDS:
                row += _pr(cells.get((t, k, name), {"tp": 0, "fp": 0, "fn": 0}))
            lines.append(f"| {name} | " + " | ".join(row) + " |")
    lines += [
        "",
        "## What could not be linked",
        "",
        "Extracted, and not turned into an identifier — so not in the graph, and a miss",
        "against the gold set. Linking is exact on purpose: a guessed link turns a recall",
        "problem into a precision problem, and the second is the one that misleads a lawyer.",
        "",
        f"Linked: {stats.linked}",
        "",
        "| reason | facts |",
        "|---|---|",
    ]
    for why, n in stats.unlinked.most_common():
        lines.append(f"| {why} | {n} |")
    for why, n in stats.rejected.most_common():
        lines.append(f"| rejected: {why} | {n} |")
    return "\n".join(lines) + "\n"
