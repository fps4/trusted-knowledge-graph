"""reports/glossary.md and reports/audit.md — generated, never typed.

Both are produced by asking the resolver as a persona, so the numbers in them are
the numbers that persona is allowed to see, and producing them is itself in the
decision record.
"""

from __future__ import annotations

import re
from pathlib import Path

import yaml


def _cell(value) -> str:
    return str(value if value not in (None, "") else "—").replace("|", "\\|").replace("\n", " ")


def _table(header: list[str], rows: list[list]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return out


# ── glossary ─────────────────────────────────────────────────────────────────
def glossary_md(active: dict, config_dir: Path, vocab_dir: Path, persona: str) -> str:
    terms = yaml.safe_load((config_dir / "glossary.yaml").read_text())["terms"]
    mapping = yaml.safe_load((config_dir / "sali-mapping.yaml").read_text())
    relations = yaml.safe_load((config_dir / "relations.yaml").read_text())["relations"]
    sali_labels = dict(
        re.findall(r'<http://lmss\.sali\.org/(\w+)>[^.]*?rdfs:label "([^"]+)"',
                   (vocab_dir / "sali-lmss-subset.ttl").read_text(), re.S)
    )
    lines = [
        "# Glossary",
        "",
        "Generated by `make glossary` from `config/glossary.yaml`, `config/sali-mapping.yaml`",
        "and `config/relations.yaml`, through the resolver. Every entry has an owner who is",
        "not an engineer. The estate and every definition are invented.",
        "",
        "## One term, four readings",
        "",
        f"`resolve_term(\"{active['label']}\")`, asked as **{persona}**. Each count went",
        "through the same access decision as any other answer — asked as someone screened",
        "from a matter it counts, a reading comes back refused rather than silently short.",
        "",
    ]
    lines += _table(
        ["reading", "owner", "definition", "count"],
        [[r["key"], r["owner"], r["definition"],
          r.get("count") if r.get("count") is not None else r.get("outcome")]
         for r in active["readings"]],
    )
    lines += [
        "",
        f"`on_ambiguous: {active['on_ambiguous']}` — a question that names the term without",
        "choosing a reading is refused at the router, with these readings listed back.",
        "",
        "## Terms",
        "",
    ]
    lines += _table(
        ["term", "also", "owner", "means", "definition"],
        [[t["label"], ", ".join(t.get("alt", [])), t["owner"],
          "; ".join(f"{k} = {v}" for k, v in (t.get("means") or {}).items()) or
          (f"{len(t['readings'])} readings" if t.get("readings") else ""),
          " ".join(t["definition"].split())]
         for t in terms],
    )
    src = mapping["source"]
    lines += [
        "",
        "## The firm's vocabularies against SALI LMSS",
        "",
        f"Reuse by mapping, not adoption. SALI LMSS at commit `{src['commit'][:12]}`",
        f"({src['committed']}), namespace `{src['namespace']}`, licence {src['licence']}.",
        "No exactMatch: where the firm's concept is broader or narrower, the mapping says so.",
        "",
    ]
    rows = []
    for scheme in ("practice-area", "matter-type"):
        for concept, links in (mapping.get(scheme) or {}).items():
            for link in links:
                rows.append([scheme, concept, f"skos:{link['match']}",
                             sali_labels.get(link["sali"], link["sali"]), f"lmss:{link['sali']}"])
    lines += _table(["scheme", "firm concept", "relation", "SALI concept", "IRI"], rows)
    lines += ["", "## Relations", "",
              "Who owns each relation the graph asserts, and whether it states the present, a",
              "point in time, or a validity period.", ""]
    lines += _table(
        ["relation", "owner", "source", "time", "served by", "gated by"],
        [[f"ssf:{r['predicate']}", r["owner"], r["source"], r["time"],
          ", ".join(r["templates"]), ", ".join(r["shapes"])] for r in relations],
    )
    return "\n".join(lines) + "\n"


# ── audit ────────────────────────────────────────────────────────────────────
def audit_md(subject: dict, person: dict, trace: dict | None, reads: list[str]) -> str:
    lines = [
        "# The decision record, read by Risk & Compliance",
        "",
        "Generated by `make audit` over the last demo run, by asking the resolver as `risk` —",
        "the only persona the policy lets read the record. Those reads are themselves in the",
        f"chain: {', '.join(f'`{t}`' for t in reads)}.",
        "",
        "> **This page is as confidential as the salt.** It shows, in the clear, who was",
        "> walled off from what — exactly what the hashed record withholds from anyone but",
        "> Risk. It is committed here only because the estate is synthetic.",
        "",
        f"## Who has ever been shown anything derived from {subject['matter']}?",
        "",
        f"Derived graphs: {', '.join(f'`{g}`' for g in subject['derived_graphs']) or 'none'}.",
        "",
    ]
    if subject["shown"]:
        lines += _table(["when", "who", "trace", "question", "how"],
                        [[s["ts"], s["persona"], s["trace"], s["template"], "; ".join(s["how"])]
                         for s in subject["shown"]])
    else:
        lines.append("Nobody.")
    lines += ["", "Refused — reached it, and was not shown it:", ""]
    lines += _table(["when", "who", "trace", "question", "outcome", "rules", "items blocked"],
                    [[r["ts"], r["persona"], r["trace"], r["template"], r["outcome"],
                      ", ".join(r["rules"]), r["blocked"]] for r in subject["refused"]]) \
        if subject["refused"] else ["None."]
    lines += ["", f"## What did {person['persona']} see?", "",
              f"Between {person['since']} and {person['until']}.", ""]
    lines += _table(
        ["when", "trace", "request", "question", "outcome", "shown", "withheld", "rules"],
        [[r["ts"], r["trace"], r["request"], r["template"], r["outcome"],
          ", ".join(r["shown_matters"] + r["shown_graphs"]) or
          (f"a count over {r['counted_matters']} matters" if r["counted_matters"] else ""),
          ", ".join(r["withheld"]), ", ".join(r["rules"])]
         for r in person["requests"]],
    )
    if trace:
        rec = trace["record"]
        lines += [
            "", f"## Why was {rec['trace']} decided as it was?", "",
            f"{rec['persona']} asked `{rec.get('template')}` at {rec['ts']}. Outcome: "
            f"**{rec.get('outcome')}**, under policy `{rec.get('policy_version')}`.",
            "",
        ]
        lines += _table(["item", "allowed", "rules", "reached", "via"],
                        [[d["item"], d["allow"], ", ".join(d["rules"]), d["reached"],
                          ", ".join(d.get("via", []))] for d in rec.get("decisions", [])])
        lines += [""]
        lines += _table(["rule", "owner", "set on", "set by", "file"],
                        [[g["rule"], g.get("owner"), g.get("set_on"), g.get("set_by"),
                          g.get("source")] for g in rec.get("grounds", {}).values()])
        lines += ["", "The same grounds the person saw when it happened — it is the same record."]
    return "\n".join(lines) + "\n"
